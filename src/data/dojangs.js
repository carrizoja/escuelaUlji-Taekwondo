// Utility functions
export const getMainDojang = () => {
  return dojangs.find(dojang => dojang.featured) || dojangs[0];
};

export const getDojangsInCity = (city) => {
  return dojangs.filter(dojang => 
    dojang.address.city.toLowerCase() === city.toLowerCase()
  );
};

export const getActiveDojangs = () => {
  return dojangs.filter(dojang => dojang.status === "Activo");
};

export const formatSchedule = (schedule) => {
  return `${schedule.days.join(" y ")} de ${schedule.time}`;
};

export const getWhatsAppLink = (dojang, message = "¡Hola! Me interesa información sobre las clases de Taekwondo") => {
  const encodedMessage = encodeURIComponent(message);
  return `https://wa.me/${dojang.contact.whatsapp}?text=${encodedMessage}`;
};

